package strings;

public class StringInteger {

	public static void main(String[] args) { 
		String aa = "10";
	String bb = "20"; 
	// Convert strings to integers  
	int num11 = Integer.parseInt(aa); 
	int num22 = Integer.parseInt(bb); 
	// Add the numbers   
	int sum = num11 + num22;
	// Output the result    
	System.out.println(sum); 
	}

}
